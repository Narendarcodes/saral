def text(language: str, key: str) -> str:
    """The fixed line `key` in `language` (en-IN when the language is not one of the ten)."""
    return TEXT.get(language, TEXT[DEFAULT_LANGUAGE])[key]


def live_greeting(language: str, first_name: str | None) -> str:
    with_name, plain = LIVE_GREETING.get(language, LIVE_GREETING[DEFAULT_LANGUAGE])
    return with_name.format(name=first_name) if first_name else plain


def menu_text() -> str:
    """What the language menu says, in key order (each option in its own language)."""
    return " ".join(TEXT[code]["option"] for code in LANGUAGES)


